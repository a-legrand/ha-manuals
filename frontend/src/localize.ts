/**
 * Translate `key` into `language` (e.g. "fr", "fr-CA", "en-GB"), falling back
 * to the base language, then to English. Without `language`, uses the page
 * language, which HA sets from the user's profile. `{name}` placeholders are
 * replaced from `params`.
 */
export function localize(key: Key, language?: string, params: Record<string, string> = {}): string {
  const lang = (language ?? document.documentElement.lang ?? "en").toLowerCase();
  const text = translations[lang]?.[key] ?? translations[lang.split("-")[0]]?.[key] ?? en[key];
  return text.replace(/\{(\w+)\}/g, (_, name) => params[name] ?? "");
}
